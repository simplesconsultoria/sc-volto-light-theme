def story_page(spec: dict[str, Any], base: str, browser: Any) -> str:
    """Render one story-based page from its spec.

    :param spec: The page spec (see ``STORY_PAGES``).
    :param base: Storybook server base URL.
    :param browser: An open Chromium browser.
    :returns: The document text.
    """
    context = browser.new_context(viewport=VIEWPORT, device_scale_factor=1)
    page = context.new_page()
    allowed = base + "/"

    def route(r: Any) -> None:
        url = r.request.url
        if url.startswith(allowed) or url.startswith(("data:", "blob:")):
            r.continue_()
        else:
            r.abort()

    page.route("**/*", route)
    try:
        body = [f"<h1>{spec['h1']}</h1>", f'<p class="lede">{spec["lede"]}</p>']
        for section in spec["sections"]:
            body.append(f"  <h2>{section['h2']}</h2>")
            for title, meta, story, theme, sample in section["stories"]:
                figures = []
                caption_title = title
                for mode in ("light", "dark"):
                    got = capture(page, base, story, mode, theme, sample)
                    if sample and title is None:
                        caption_title = got["label"]
                    figures.append(
                        figure(mode.capitalize(), got["bg"], got["fg"], got["html"])
                    )
                body.append(story_block(caption_title, meta, figures))
        return page_document(spec, "\n".join(body))
    finally:
        context.close()


