def load_tokens() -> dict:
    """Run the Node exporter and parse its JSON.

    :returns: The token data.
    :raises RuntimeError: If the exporter fails.
    """
    env = {**os.environ, "NODE_NO_WARNINGS": "1"}
    result = subprocess.run(
        ["node", str(TOKENS_SCRIPT)],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"token export failed:\n{result.stderr}")
    return json.loads(result.stdout)


def main() -> None:
    """Regenerate every preview in ``docs/design-system/previews/``.

    :raises SystemExit: If the Storybook build is missing.
    """
    if not (BUILD / "index.json").exists():
        raise SystemExit(
            f"No Storybook build at {BUILD}. Run: make -C frontend storybook-build"
        )
    tokens = load_tokens()
    OUT.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    with _StaticServer(BUILD) as base, sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        try:
            for spec in STORY_PAGES:
                written[spec["file"]] = story_page(spec, base, browser)
            written["block-widths.html"] = matrix_page(
                NEW_STORY_PAGES[0], base, browser, widths_rows(tokens)
            )
            written["block-borders.html"] = matrix_page(
                NEW_STORY_PAGES[1], base, browser, borders_rows()
            )
            written["color-group-layers.html"] = matrix_page(
                NEW_STORY_PAGES[2], base, browser, layers_rows()
            )
        finally:
            browser.close()

    written["colors.html"] = colors_page(tokens)
    written["typography.html"] = typography_page(tokens)
    written["block-themes.html"] = block_themes_page(tokens)
    written["color-groups.html"] = color_groups_page(tokens)

    for name, text in sorted(written.items()):
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote {OUT / name} ({len(text.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
