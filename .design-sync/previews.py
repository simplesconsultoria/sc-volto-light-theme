def color_groups_page(tokens: dict) -> str:
    """Render the Color Group token card: base groups, the ``--theme-*`` mapping, and the 16 pairs.

    :param tokens: The exported token data.
    :returns: The document text.
    """
    roles = ("bg", "text", "subtext", "accent")
    head = "".join(f"<th>{r}</th>" for r in roles)
    group_rows = []
    for gid in tokens["baseColorGroupIds"]:
        cells = []
        for role in roles:
            light, dark = group_value(tokens, gid, role)
            cells.append(f"<td>{chip(light, dark, f'{gid} {role}')}</td>")
        group_rows.append(f"<tr><td><code>{gid}</code></td>{''.join(cells)}</tr>")
    themes = tokens["themeMappings"]
    keys = list(themes["default"].keys())
    map_rows = "".join(
        f"<tr><td><code>{k}</code></td>"
        f"<td><code>{html.escape(themes['default'][k])}</code></td>"
        f"<td><code>{html.escape(themes['alternative'][k])}</code></td></tr>"
        for k in keys
    )
    pairs = []
    for pair in tokens["customPairs"]:
        back, front = pair["back"], pair["front"]
        bl, _bd = group_value(tokens, back, "bg")
        fl, _fd = group_value(tokens, front, "bg")
        _tl, _td = group_value(tokens, back, "text")
        pairs.append(
            '<div class="chip"><div class="halves">'
            f'<i style="background:{html.escape(bl)}"></i><i style="background:{html.escape(fl)}"></i>'
            f'</div><div class="meta"><code>custom-{back}-{front}</code>'
            f"back {back} · front {front}</div></div>"
        )
    body = [
        "<h1>Color groups</h1>",
        '<p class="lede">The four base Color Groups, each with a background, text, subtext and accent '
        "role, read from <code>DEFAULT_COLOR_GROUPS</code>. Each role is a light and dark value. The "
        "block theme mapping and the sixteen <code>custom-{back}-{front}</code> pairs are built from the "
        "same groups.</p>",
        "  <h2>Base Color Groups (light / dark)</h2>",
        f"<table><tr><th>Group</th>{head}</tr>{''.join(group_rows)}</table>",
        "  <h2>Theme mapping (<code>--theme-*</code>)</h2>",
        f"<table><tr><th>Property</th><th>default</th><th>alternative</th></tr>{map_rows}</table>",
        "  <h2>Custom ColorGroup pairs (custom-{back}-{front})</h2>",
        '<div class="chips">' + "".join(pairs) + "</div>",
    ]
    return page(
        "Color groups",
        "Colors",
        "Color Group token card",
        "\n".join(body),
        f"{GENERATOR} from <code>config/blockThemes.ts</code> and <code>helpers/themeStyles.ts</code>.",
    )


