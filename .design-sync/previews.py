def page(title: str, group: str, description: str, body: str, footer: str) -> str:
    """Assemble one self-contained preview document.

    :param title: Page title (also the ``<title>``).
    :param group: The ``@dsCard`` group.
    :param description: One line describing the page for the header comment.
    :param body: The inner HTML of the page wrapper.
    :param footer: The footer HTML.
    :returns: The full document, starting with the ``@dsCard`` marker.
    """
    css = CHROME_CSS.replace("%ZOOM%", FRAME_ZOOM)
    return (
        f'<!-- @dsCard group="{group}" -->\n'
        "<!--\n"
        f"  {description} — @simplesconsultoria/volto-light-theme\n"
        "  Generated by make design-previews. Do not edit by hand; change the\n"
        "  generator or its sources and run the target again.\n"
        "-->\n"
        '<meta charset="utf-8" />\n'
        f"<title>{title}</title>\n"
        f"<style>{css}</style>\n"
        f'<div class="wrap">\n{body}\n'
        f"  <footer>{footer}</footer>\n"
        "</div>\n"
    )


def figure(mode: str, bg: str, fg: str, fit_html: str) -> str:
    """One light or dark stage.

    :param mode: ``Light`` or ``Dark`` (the caption).
    :param bg: Stage background color.
    :param fg: Stage text color.
    :param fit_html: The captured content.
    :returns: The ``<figure>`` markup.
    """
    return (
        f"      <figure>\n        <figcaption>{mode}</figcaption>\n"
        f'        <div class="stage" style="background:{bg};color:{fg}">{fit_html}</div>\n'
        "      </figure>"
    )


def story_block(title: str, meta: str, figures: list[str]) -> str:
    """One story: a head row over its light and dark stages.

    :param title: Bold head text.
    :param meta: Right-hand description (may contain markup).
    :param figures: The ``figure()`` markup, light then dark.
    :returns: The ``.story`` markup.
    """
    return (
        '  <div class="story">\n'
        f'    <div class="head"><b>{title}</b><span>{meta}</span></div>\n'
        '    <div class="modes">\n' + "\n".join(figures) + "\n    </div>\n  </div>"
    )


def chip(light: str, dark: str, name: str) -> str:
    """A color chip showing the light and dark value of one token.

    :param light: Light-mode color.
    :param dark: Dark-mode color.
    :param name: Token or value label.
    :returns: The chip markup.
    """
    return (
        '<div class="chip">'
        f'<div class="halves"><i style="background:{html.escape(light)}"></i>'
        f'<i style="background:{html.escape(dark)}"></i></div>'
        f'<div class="meta"><code>{html.escape(name)}</code>'
        f"{html.escape(light)} / {html.escape(dark)}</div></div>"
    )


