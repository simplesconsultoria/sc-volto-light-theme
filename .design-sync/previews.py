# Live-page JavaScript. It takes the story root, finds the themed wrapper that
# carries the color scheme, and returns the content as a static, inlined copy.
MATERIALISE_JS = r"""
(args) => {
  const SVG_NS = 'http://www.w3.org/2000/svg';
  const INHERITED = new Set(args.inherited);
  const DROP = args.drop;
  const REPLACED = new Set(['img', 'svg', 'canvas', 'input', 'select', 'textarea', 'button']);
  const SKIP = new Set(['script', 'style', 'link', 'meta', 'noscript', 'template', 'source', 'track']);
  const placeholder = args.placeholder;

  const frame = document.createElement('iframe');
  frame.style.cssText = 'position:absolute;width:0;height:0;border:0;visibility:hidden';
  document.body.appendChild(frame);
  const pdoc = frame.contentDocument;
  const pwin = frame.contentWindow;

  const cache = new Map();
  // `link`: the copy keeps an href (rewritten to `#`), which gives an `a` the
  // UA link colour, so its defaults are measured with one too.
  const initialFor = (tag, ns, link = false) => {
    const key = (ns === SVG_NS ? 'svg:' : 'html:') + tag + (link ? ':link' : '');
    if (!cache.has(key)) {
      const el = ns === SVG_NS ? pdoc.createElementNS(SVG_NS, tag) : pdoc.createElement(tag);
      if (link) el.setAttribute('href', '#');
      pdoc.body.appendChild(el);
      const cs = pwin.getComputedStyle(el);
      const out = {};
      for (let i = 0; i < cs.length; i++) {
        const p = cs[i];
        if (!(p[0] === '-' && p[1] === '-')) out[p] = cs.getPropertyValue(p);
      }
      el.remove();
      cache.set(key, out);
    }
    return cache.get(key);
  };

  const declare = (cs, parentCS, tag, ns, extraDrop, link = false) => {
    const init = initialFor(tag, ns, link);
    // What an element gets when its UA style leaves a property alone.
    const plain = initialFor(ns === SVG_NS ? 'g' : 'span', ns);
    const replaced = REPLACED.has(tag) || tag === 'img';
    const parts = [];
    for (const p of Object.keys(init)) {
      if (DROP.some((d) => p.startsWith(d))) continue;
      if (extraDrop.includes(p)) continue;
      if (!replaced && (p === 'width' || p === 'height')) continue;
      let v = cs.getPropertyValue(p);
      if (v === '') continue;
      const raw = v;
      if (INHERITED.has(p)) {
        // The copy inherits from its parent unless the UA styles the tag
        // itself (a link's colour, a heading's weight), in which case it gets
        // the UA value: only a value matching what it will get can be left out.
        const uaStyled = init[p] !== plain[p];
        const ref = uaStyled ? init[p] : parentCS ? parentCS.getPropertyValue(p) : init[p];
        if (ref === raw) continue;
      } else if (init[p] === raw) {
        continue;
      }
      if (v.includes('url(')) {
        v = v.replace(/url\((?!["']?data:)[^)]*\)/g, 'url("' + placeholder + '")');
      }
      parts.push(p + ':' + v);
    }
    return parts.join(';');
  };

  const pseudo = (src, cs, which) => {
    const pcs = getComputedStyle(src, which);
    const content = pcs.getPropertyValue('content');
    if (!content || content === 'none' || content === 'normal') return null;
    const span = document.createElement('span');
    span.setAttribute('aria-hidden', 'true');
    const m = /^"(.*)"$/s.exec(content) || /^'(.*)'$/s.exec(content);
    span.textContent = m ? m[1].replace(/\\"/g, '"') : '';
    const style = declare(pcs, cs, 'span', null, []);
    if (style) span.setAttribute('style', style);
    return span;
  };

  const snapshot = (src, parentCS) => {
    if (src.nodeType === Node.TEXT_NODE) return document.createTextNode(src.nodeValue);
    if (src.nodeType !== Node.ELEMENT_NODE) return null;
    const tag = src.localName;
    const ns = src.namespaceURI;
    if (SKIP.has(tag)) return null;
    const cs = getComputedStyle(src);
    let out;
    if (['iframe', 'video', 'audio', 'object', 'embed', 'picture'].includes(tag)) {
      out = document.createElement(tag === 'picture' ? 'span' : 'img');
      if (out.tagName === 'IMG') {
        out.setAttribute('src', placeholder);
        out.setAttribute('alt', '');
        out.setAttribute('style', declare(cs, parentCS, 'img', null, []));
        return out;
      }
    } else {
      out = ns === SVG_NS ? document.createElementNS(SVG_NS, tag) : document.createElement(tag);
    }
    for (const a of Array.from(src.attributes)) {
      const n = a.name;
      if (n === 'style' || n === 'srcset' || n === 'sizes' || n === 'loading' ||
          n === 'decoding' || n === 'crossorigin' || n === 'integrity' ||
          n === 'referrerpolicy' || n.startsWith('on')) continue;
      let v = a.value;
      if (n === 'src' && tag === 'img') v = placeholder;
      else if (n === 'href' || n === 'xlink:href' || n === 'action' || n === 'formaction') {
        if (!v.startsWith('#')) v = '#';
      } else if (n === 'src' || n === 'poster' || n === 'data') {
        if (!v.startsWith('data:')) v = placeholder;
      }
      try { out.setAttributeNS(a.namespaceURI, n, v); } catch (e) { /* skip */ }
    }
    const link = tag === 'a' && src.hasAttribute('href');
    const style = declare(cs, parentCS, tag, ns, [], link);
    if (style) out.setAttribute('style', style);
    const before = pseudo(src, cs, '::before');
    if (before) out.appendChild(before);
    for (const child of Array.from(src.childNodes)) {
      const c = snapshot(child, cs);
      if (c) out.appendChild(c);
    }
    const after = pseudo(src, cs, '::after');
    if (after) out.appendChild(after);
    return out;
  };

  const root = document.querySelector('#storybook-root');
  const themed = root.querySelector('div[style*="color-scheme"]') || root.firstElementChild;
  const themedCS = getComputedStyle(themed);
  const fit = document.createElement('div');
  fit.className = 'fit';
  fit.setAttribute('style', declare(themedCS, null, 'div', null, ['min-height']));

  let nodes = Array.from(themed.childNodes);
  let label = null;
  if (args.label) {
    const p = Array.from(themed.querySelectorAll('p')).find((x) => {
      const t = x.textContent.trim();
      return t === args.label || t.startsWith(args.label);
    });
    if (!p) throw new Error('sample label not found: ' + args.label);
    label = p.textContent.trim();
    nodes = Array.from(p.parentElement.childNodes).filter((n) => n !== p);
  }
  for (const n of nodes) {
    const c = snapshot(n, themedCS);
    if (c) fit.appendChild(c);
  }
  frame.remove();
  return { label, bg: themedCS.backgroundColor, fg: themedCS.color, html: fit.outerHTML };
}
"""


class _QuietHandler(http.server.SimpleHTTPRequestHandler):
    """Static file handler that does not log each request."""

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002
        """Silence the request log.

        :param format: Log format string (unused).
        :param args: Log arguments (unused).
        """


class _StaticServer:
    """Serve the Storybook build on a free localhost port for the duration of a run."""

    def __init__(self, directory: Path) -> None:
        """Remember the directory to serve.

        :param directory: The Storybook build output.
        """
        self.directory = directory
        self.server: socketserver.TCPServer | None = None
        self.thread: threading.Thread | None = None

    def __enter__(self) -> str:
        """Start the server in a background thread.

        :returns: The base URL, without a trailing slash.
        """
        handler = lambda *a, **k: _QuietHandler(*a, directory=str(self.directory), **k)
        self.server = socketserver.ThreadingTCPServer(("127.0.0.1", 0), handler)
        self.server.daemon_threads = True
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        port = self.server.server_address[1]
        return f"http://127.0.0.1:{port}"

    def __exit__(self, *exc: object) -> None:
        """Stop the server and release the port."""
        if self.server is not None:
            self.server.shutdown()
            self.server.server_close()


def capture(
    page: Any, base: str, story: str, mode: str, theme: str, label: str | None = None
) -> dict:
    """Capture one rendered story as a static, inlined fragment.

    :param page: An open Playwright page.
    :param base: Base URL of the running Storybook server.
    :param story: Storybook story id.
    :param mode: ``light`` or ``dark``, the ``colorMode`` global.
    :param theme: Block theme id, the ``blockTheme`` global.
    :param label: Optional prefix of a matrix sample's label to capture alone.
    :returns: Dict with ``label``, ``bg``, ``fg`` and ``html``.
    :raises RuntimeError: If the story does not render.
    """
    url = (
        f"{base}/iframe.html?id={story}&viewMode=story"
        f"&globals=colorMode:{mode};blockTheme:{theme}"
    )
    page.goto(url, wait_until="load")
    page.wait_for_function(
        "() => { const r = document.querySelector('#storybook-root');"
        " return !!r && r.querySelectorAll('*').length > 3; }",
        timeout=60000,
    )
    page.evaluate("() => document.fonts.ready.then(() => true)")
    page.wait_for_timeout(250)
    result = page.evaluate(
        MATERIALISE_JS,
        {
            "label": label,
            "placeholder": PLACEHOLDER,
            "inherited": INHERITED,
            "drop": DROP_PREFIXES,
        },
    )
    if not result["html"] or "<div" not in result["html"]:
        raise RuntimeError(f"empty capture for {story} ({mode}, {theme})")
    return result


