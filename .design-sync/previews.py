def split_top_level(text: str) -> list[str]:
    """Split a comma-separated CSS argument list, ignoring commas inside parentheses.

    :param text: The argument list, without the outer parentheses.
    :returns: The trimmed arguments.
    """
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def light_dark(value: str) -> tuple[str, str]:
    """Split a ``light-dark()`` value into its light and dark halves.

    :param value: A CSS value, possibly ``light-dark(<light>, <dark>)``.
    :returns: ``(light, dark)``; a plain value is returned for both.
    """
    value = value.strip()
    m = re.match(r"^light-dark\((.*)\)$", value, re.S)
    if not m:
        return value, value
    light, dark = split_top_level(m.group(1))[:2]
    return light, dark


def root_declarations() -> list[tuple[str, str]]:
    """Read the custom property declarations inside ``:root`` in ``_root.scss``.

    :returns: ``(name, value)`` pairs in source order, comments removed.
    """
    text = (THEME_DIR / "_root.scss").read_text(encoding="utf-8")
    text = re.sub(r"//[^\n]*", "", text)
    start = text.index(":root {") + len(":root {")
    depth, end = 1, start
    while depth:
        ch = text[end]
        depth += ch == "{"
        depth -= ch == "}"
        end += 1
    body = text[start : end - 1]
    return [
        (m.group(1), " ".join(m.group(2).split()))
        for m in re.finditer(r"--([\w-]+)\s*:\s*([^;]+);", body)
    ]


def scss_maps() -> dict[str, Any]:
    """Read the type maps and scalar overrides from ``_variables.scss``.

    :returns: ``font_sizes``, ``line_heights`` (token -> rem) and ``scalars``.
    """
    text = (THEME_DIR / "_variables.scss").read_text(encoding="utf-8")
    text = re.sub(r"//[^\n]*", "", text)

    def mapping(name: str) -> dict[str, str]:
        block = re.search(rf"\${name}:\s*\((.*?)\);", text, re.S)
        if not block:
            return {}
        return dict(re.findall(r"([\w-]+):\s*([\d.]+rem)", block.group(1)))

    scalars = {
        name: value.strip()
        for name, value in re.findall(r"^\$([\w-]+):\s*([^;(]+?);", text, re.M)
    }
    return {
        "font_sizes": mapping("font-sizes"),
        "line_heights": mapping("line-heights"),
        "scalars": scalars,
    }


def heading_rules() -> list[tuple[str, str]]:
    """List the rules in ``_typography.scss`` that set a font size from the scale.

    :returns: ``(selector context, scale token)`` pairs in source order.
    """
    rules: list[tuple[str, str]] = []
    context = ""
    for line in (
        (THEME_DIR / "_typography.scss").read_text(encoding="utf-8").splitlines()
    ):
        stripped = line.strip()
        if stripped.endswith("{") and not stripped.startswith("@media"):
            context = stripped.rstrip("{").strip()
        for key in re.findall(r"map-get\(\$font-sizes,\s*([\w-]+)\)", stripped):
            rules.append((context, key))
    return rules


def group_value(tokens: dict, group: str, role: str) -> tuple[str, str]:
    """Return the light and dark value of one Color Group role.

    :param tokens: The exported token data.
    :param group: Color group id, for example ``accent``.
    :param role: One of ``bg``, ``text``, ``subtext``, ``accent``.
    :returns: ``(light, dark)``.
    """
    return light_dark(tokens["colorGroupProps"][group][f"--colorgroup-{group}-{role}"])


def resolve(expr: str, tokens: dict, mode: str) -> str:
    """Resolve a ``var(--colorgroup-*)`` expression to a concrete color for one mode.

    :param expr: A property value such as ``var(--colorgroup-accent-bg)``.
    :param tokens: The exported token data.
    :param mode: ``light`` or ``dark``.
    :returns: The color, or the expression unchanged when it is not a group token.
    """
    m = re.match(r"var\(--colorgroup-(\w+?)-(bg|text|subtext|accent)\)$", expr.strip())
    if not m:
        return expr
    light, dark = group_value(tokens, m.group(1), m.group(2))
    return light if mode == "light" else dark


